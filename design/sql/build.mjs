import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const directory = new URL('./', import.meta.url);
const output = new URL('../../mods/ade/sql-parser-vendor.js', directory);
const lock = JSON.parse(await readFile(new URL('package-lock.json', directory), 'utf8'));
const source = await readFile(new URL('node_modules/@codemirror/lang-sql/dist/index.js', directory), 'utf8');
const sourceHash = createHash('sha256').update(source).digest('hex');
// Guard the small parsing-only adaptation below against upstream source changes.
const expectedHash = '1bfaf09ca4ba779687f638bb19564e56b66eae3ba1812fda72b1cc2c7cf296d5';
if (sourceHash !== expectedHash) throw new Error('Pinned SQL source changed; review parser adapter');
const notices = [];
const result = await build({
  absWorkingDir: directory.pathname, entryPoints: ['vendor-entry.js'], bundle: true,
  format: 'esm', platform: 'neutral', target: 'es2020', write: false,
  minify: true, legalComments: 'none', metafile: true, define: {process: 'undefined'},
  plugins: [{name: 'sql-parser-only', setup(builder) {
    builder.onLoad({filter: /\/node_modules\/@codemirror\/lang-sql\/dist\/index\.js$/}, () => {
      let code = source.replace(/^import .* from '@codemirror\/(?:language|autocomplete)';\n/gm, '')
        .replace(/^import .* from '@lezer\/highlight';\n/gm, '');
      const start = code.indexOf('let parser = /*@__PURE__*/parser$1.configure({');
      const end = code.indexOf('class SQLDialect {', start);
      if (start < 0 || end < 0) throw new Error('SQL parser adapter anchors missing');
      code = code.slice(0, start) + 'let parser = parser$1;\n' + code.slice(end);
      code = code.replace('let language = LRLanguage.define({', 'let language = ({');
      return {contents: code, loader: 'js'};
    });
  }}],
});
if (Object.values(result.metafile.outputs).some(item => item.imports.length)) throw new Error('Vendor must be self-contained');
const packages = [...new Set(Object.keys(result.metafile.inputs).map(path =>
  path.match(/node_modules\/(\@[^/]+\/[^/]+|[^/]+)/)?.[1]).filter(Boolean))].sort();
packages.push('esbuild');
for (const name of packages) {
  const pkg = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, directory), 'utf8'));
  if (pkg.version !== lock.packages[`node_modules/${name}`].version || pkg.license !== 'MIT') throw new Error(`Unexpected package ${name}`);
  const license = await readFile(new URL(`node_modules/${name}/${name === 'esbuild' ? 'LICENSE.md' : 'LICENSE'}`, directory), 'utf8');
  notices.push(`${name}@${pkg.version}${name === 'esbuild' ? ' (build only)' : ''}\n\n${license}`);
}
const licenseText = '# SQL parser vendor licenses\n\nGenerated from package-lock.json by build.mjs.\n\n' + notices.join('\n---\n\n');
const code = '// GENERATED by design/sql/build.mjs; npm ci && npm run build in design/sql.\n' +
  '// Parsing-only adapter: upstream grammar, tokenizer and dialect definitions; no editor/DOM services.\n/*\n' +
  notices.slice(0, -1).join('\n---\n\n') + '\n*/\n' + result.outputFiles[0].text;
if (/\b(?:document|window|process)\s*[.\[]|\brequire\s*\(|node:|\beval\s*\(|new Function/.test(code)) throw new Error('Unexpected host dependency in SQL parser bundle');
const licenseFile = new URL('THIRD_PARTY_LICENSES.md', directory);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== code || await readFile(licenseFile, 'utf8') !== licenseText) throw new Error('SQL vendor differs; npm run build');
  console.log('PASS reproducible SQL parser vendor');
} else {
  await writeFile(output, code);
  await writeFile(licenseFile, licenseText);
  console.log(`Built SQL parser vendor (${Buffer.byteLength(code)} bytes)`);
}
