import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const directory = new URL('./', import.meta.url);
const modIndex = process.argv.indexOf('--mod');
const targetMod = modIndex < 0 ? 'codenav' : process.argv[modIndex + 1];
if (!targetMod || !/^[a-z0-9][a-z0-9-]*$/.test(targetMod)) throw new Error('Expected --mod NAME');
const output = new URL(`../../mods/${targetMod}/editor-state-vendor.js`, directory);
const dependencies = [
  ['@codemirror/state', '6.7.6', 'LICENSE'],
  ['@marijn/find-cluster-break', '1.0.4', 'LICENSE'],
  ['unicode-segmenter', '0.17.3', 'LICENSE'],
  ['esbuild', '0.28.2', 'LICENSE.md'],
];
const notices = await Promise.all(dependencies.map(async ([name, version, license]) => {
  const metadata = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, directory), 'utf8'));
  if (metadata.version !== version || metadata.license !== 'MIT') throw new Error(`Unexpected dependency: ${name}`);
  return `${name}@${version}${name === 'esbuild' ? ' (build tool only)' : ''}\n\n${await readFile(new URL(`node_modules/${name}/${license}`, directory), 'utf8')}`;
}));
const licenseFile = new URL('THIRD_PARTY_LICENSES.md', directory);
const licenseText = '# Editor vendor licenses\n\nGenerated from the exact pinned npm packages by build.mjs.\nUnicode segmentation data: Unicode 17.0.0 (unicode-segmenter package).\n\n' + notices.join('\n---\n\n');
const result = await build({
  absWorkingDir: directory.pathname, entryPoints: ['vendor-entry.js'], bundle: true,
  format: 'esm', platform: 'neutral', target: 'es2020', write: false,
  minify: true, legalComments: 'inline', metafile: true,
  banner: { js: '// GENERATED by design/editor/build.mjs; npm ci && npm run build in design/editor.\n// Full runtime dependency licenses follow, including when deployed without design/.\n/*\n' + notices.slice(0, 3).join('\n---\n\n') + '\n*/' },
});
if (Object.values(result.metafile.outputs).some(output => output.imports.length)) throw new Error('Vendor bundle must be self-contained');
const code = result.outputFiles[0].text;
if (/\b(?:document|window|process)\s*[.\[]|\brequire\s*\(|node:|\beval\s*\(|new Function/.test(code)) throw new Error('Unexpected host dependency in vendor bundle');
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== code) throw new Error('Vendor differs; run npm run build');
  if (await readFile(licenseFile, 'utf8') !== licenseText) throw new Error('License notices differ; run npm run build');
  console.log('PASS reproducible self-contained editor vendor');
} else {
  await writeFile(output, code);
  await writeFile(licenseFile, licenseText);
  console.log(`Built editor vendor (${Buffer.byteLength(code)} bytes)`);
}
