#!/usr/bin/env python3
"""Generate standalone UI modules; --check checks drift, --mod adds a target."""
import argparse
import json
from pathlib import Path
import sys
import re
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
HEADER = '// GENERATED by design/idea/sync_ui.py; edit design/idea/ui.js or tokens.json.\n'
ICON_HEADER = '// GENERATED by design/idea/sync_ui.py; edit design/idea/icons.json or icons/.\n'

def icon_source():
    registry = json.loads((HERE / 'icons.json').read_text())
    roles, aliases = registry['roles'], registry['aliases']
    names = {**roles, **aliases}
    if set(roles) & set(aliases):
        raise ValueError('Icon roles and aliases must have distinct names')
    if registry['fallback'] not in names:
        raise ValueError('Missing fallback icon role')
    for alias, role in aliases.items():
        if role not in roles:
            raise ValueError(f'Unknown icon alias target: {alias} -> {role}')
    assets = {}
    for asset in set(roles.values()):
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', asset):
            raise ValueError(f'Invalid icon asset name: {asset}')
        path = HERE / 'icons' / f'{asset}.svg'
        content = path.read_text()
        attributes = ET.fromstring(content).attrib
        expected = {'viewBox': '0 0 24 24', 'fill': 'none', 'stroke': 'currentColor',
                    'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round'}
        if any(attributes.get(key) != value for key, value in expected.items()):
            raise ValueError(f'Icon does not follow shared stroke rules: {path}')
        assets[f'ui-icons/{asset}.svg'] = content
    for name in ['LICENSE', 'UPSTREAM.md']:
        assets[f'ui-icons/{name}'] = (HERE / 'icons' / name).read_text()
    return registry, assets


def icon_module(mod, registry):
    roles = json.dumps(registry['roles'], ensure_ascii=False, indent=2)
    aliases = json.dumps(registry['aliases'], ensure_ascii=False, indent=2)
    fallback = json.dumps(registry['fallback'])
    return ICON_HEADER + f'''import {{ svg }} from "gpui-kit";

const roles = Object.freeze({roles});
const aliases = Object.freeze({aliases});
const own = (object, key) => Object.prototype.hasOwnProperty.call(object, key);
export function uiIconPath(role) {{
  const name = typeof role === "string" ? role : "";
  const key = own(aliases, name) ? aliases[name] : name;
  const fallback = aliases[{fallback}] ?? {fallback};
  const asset = own(roles, key) ? roles[key] : roles[fallback];
  return `mods/{mod}/ui-icons/${{asset}}.svg`;
}}
export const uiIcon = (role, size = 16) => svg(uiIconPath(role)).size(size).flex_none();
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--mod', action='append', help='existing mod name, repeatable')
    args = parser.parse_args()
    mods = args.mod or ['codenav', 'activity']
    ui = HEADER + (HERE / 'ui.js').read_text()
    tokens = json.loads((HERE / 'tokens.json').read_text())
    generated = HEADER + 'export const IDEA_TOKENS = ' + json.dumps(tokens, indent=2, ensure_ascii=False) + ';\n'
    registry, assets = icon_source()
    drift = []
    for mod in mods:
        if not mod or not all(c.isalnum() or c in '-_' for c in mod):
            parser.error(f'invalid mod name: {mod!r}')
        folder = ROOT / 'mods' / mod
        if not folder.is_dir():
            parser.error(f'mod directory does not exist: {folder}')
        outputs = {'idea-design.js': ui, 'idea-tokens.js': generated,
                   'ui-icons.js': icon_module(mod, registry), **assets}
        if mod in ['codenav', 'ade']:
            outputs['http-client.js'] = '// GENERATED by design/idea/sync_ui.py; edit design/idea/http-client.js.\n' + (HERE / 'http-client.js').read_text()
            outputs['terminal-paths.js'] = '// GENERATED by design/idea/sync_ui.py; edit design/idea/terminal-paths.js.\n' + (HERE / 'terminal-paths.js').read_text()
        if mod == 'ade':
            source_model = (ROOT / 'mods/codenav/editor-model.js').read_text()
            outputs['navigation-markers.js'] = '// GENERATED by design/idea/sync_ui.py; edit navigationMarkers in mods/codenav/editor-model.js.\n' + source_model[source_model.index('export function navigationMarkers('):]
        for name, contents in outputs.items():
            target = folder / name
            if not target.exists() or target.read_text() != contents:
                drift.append(str(target.relative_to(ROOT)))
                if not args.check:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(contents)
        for target in sorted((folder / 'ui-icons').glob('*.svg')):
            if str(target.relative_to(folder)) not in outputs:
                drift.append(str(target.relative_to(ROOT)))
                if not args.check:
                    target.unlink()
    if args.check and drift:
        print('Generated UI drift:\n' + '\n'.join(drift), file=sys.stderr)
        return 1
    print(('Checked' if args.check else 'Generated') + ': ' + ', '.join(mods))
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
