import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import { createFrameLayout, toggleRegion, arrangeRegions, regionSettings, projectDimensions } from '../../mods/ade/frame-layout.js';

const metrics = { appbarHeight: 48, statusHeight: 26, stripeWidth: 44, leftWidth: 218, rightWidth: 244, lowerHeight: 180, radius: 4, splitterWidth: 6, toolHeaderHeight: 36, tabHeight: 40 };
const store = new Map(), writes = [], projectA = { id: 'a' }, projectB = { id: 'b' };
let current = projectA;
const context = vm.createContext({});
const module = new vm.SourceTextModule(await fs.readFile(new URL('../../mods/ade/project-tools.js', import.meta.url), 'utf8'), { context });
await module.link(async name => {
  if (name === './frame-layout.js') return new vm.SourceTextModule(await fs.readFile(new URL('../../mods/ade/frame-layout.js', import.meta.url), 'utf8'), { context });
  const values = name === 'herdr' ? { shared: key => store.get(key), setShared: (key, value) => { writes.push(key); store.set(key, value); } }
    : { currentProject: () => current, projectKey: project => project.id };
  return new vm.SyntheticModule(Object.keys(values), function () { for (const [key, value] of Object.entries(values)) this.setExport(key, value); }, { context });
});
await module.evaluate();
const api = module.namespace, plain = value => JSON.parse(JSON.stringify(value));
const nodes = tree => [tree, ...(tree.children ?? []).flatMap(nodes)];
const find = (tree, id) => nodes(tree).find(node => node.id === id);
let frame = createFrameLayout(metrics);
const defaults = JSON.parse(JSON.stringify(frame));
store.set('ade.project-dimensions', { a: { ...projectDimensions(frame), 'ade-left': { px: 333 } } });
frame = api.restoreProjectTools(frame, api.initialProjectTools(projectA, frame));
assert.equal(find(frame, 'ade-left').size.px, 333, 'existing project dimensions migrate');
frame = toggleRegion(frame, 'project');
frame = toggleRegion(frame, 'database');
frame = toggleRegion(frame, 'results');
const stateA = api.captureProjectTools(frame);
api.saveProjectTools(projectA, stateA);
const writesBefore = writes.length;
api.saveProjectTools(projectA, stateA);
assert.equal(writes.length, writesBefore, 'unchanged snapshots do not churn shared state');
current = projectB;
frame = api.restoreProjectTools(frame, api.savedProjectTools(projectB));
assert.deepEqual(plain(regionSettings(frame)), plain(regionSettings(defaults)), 'first visit uses stable defaults');
assert.equal(find(frame, 'ade-left').size.px, 218, 'new projects do not inherit previous project widths');
frame = arrangeRegions(frame, { terminal: { position: 'bottom', hidden: false }, results: { hidden: true }, database: { hidden: true } });
find(frame, 'ade-right').size = { px: 410 };
api.saveProjectTools(projectB, api.captureProjectTools(frame));
const stateB = api.savedProjectTools(projectB);
current = projectA;
frame = api.restoreProjectTools(frame, api.savedProjectTools(projectA));
assert.equal(regionSettings(frame, stateA.tools).project.hidden, true);
assert.equal(regionSettings(frame, stateA.tools).database.hidden, false);
assert.equal(regionSettings(frame, stateA.tools).results.hidden, true);
assert.equal(regionSettings(frame, stateA.tools).terminal.position, 'right-bottom');
assert.equal(find(frame, 'ade-left').size.px, 333);
assert.equal(api.restoreProjectTools(frame, stateA), frame, 'restoration is idempotent');
assert.deepEqual(plain(api.toolSettings()), plain(stateA.tools));
current = projectB;
frame = api.restoreProjectTools(frame, stateB);
assert.equal(regionSettings(frame, stateB.tools).project.hidden, false);
assert.equal(regionSettings(frame, stateB.tools).terminal.position, 'bottom');
assert.equal(regionSettings(frame, stateB.tools).terminal.hidden, false);
assert.equal(find(frame, 'ade-right').size.px, 410);
assert.equal(find(frame, 'ade-terminal-body').content.tab, 'active');
assert.equal(store.has('ade.tool-settings'), false, 'project changes never write global tool metadata');
assert.deepEqual(plain(api.savedProjectTools(projectA)), plain(stateA));
console.log('PASS project tools: independent visibility/active slot/placement/sizes, stable new-project defaults, dimension migration, idempotence and global catalog preservation');
